// Helper function
export const calculateRenewalDate = (billingCycle: 'monthly' | 'yearly'): Date => {
  const date = new Date();
  if (billingCycle === 'monthly') {
    date.setMonth(date.getMonth() + 1);
  } else {
    date.setFullYear(date.getFullYear() + 1);
  }
  return date;
};

export const calculatePeriodEnd = (days: number): Date => {
  const endDate = new Date();
  endDate.setDate(endDate.getDate() + days);
  return endDate;
};